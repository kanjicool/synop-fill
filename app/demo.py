def make_chunk(code: str, b: str, c: str, d: str, e: str, f: str) -> str:
    """สร้างข้อความของสถานีหนึ่งแห่งจากค่าที่ลงในตาราง (ถอดกลับแล้วต้องได้ค่าเดิม)"""
    calm = b == "ลมสงบ"
    t = float(f)
    tt = round(abs(t) * 10)
    dew = round((t - 3) * 10)
    groups = [
        code,
        "31460" if e else "32460",
        _N[d] + _DD[b] + ("00" if calm else _FF[c]),
        "1" + ("1" if t < 0 else "0") + f"{tt:03d}",
        "2" + ("1" if dew < 0 else "0") + f"{abs(dew):03d}",
    ]
    if e:
        groups.append("7" + _WW[e] + "00")
    return " ".join(groups)


def make_message(hdr: str, code: str, b: str, c: str, d: str, e: str, f: str) -> str:
    return f"AAXX {hdr}\n{make_chunk(code, b, c, d, e, f)}"


